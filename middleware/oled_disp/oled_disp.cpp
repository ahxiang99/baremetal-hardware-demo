Result<> oled_disp::initialize(const Stm32Spi &spi, const GPIO_Config &rst_cfg, const GPIO_Config &dc_cfg, const GPIO_Config &cs_cfg, const MySysTick &systick)
{
    TRY(disp_.initialize(spi, rst_cfg, dc_cfg, cs_cfg, systick));
    screen_width_ = SCR_W;
    screen_height_ = SCR_H;
    vram_.fill(0x00);
    disp_.flush(vram_);
    return Ok();
}

void oled_disp::display_on()
{
    disp_.set_disp_state(LCD_ON);
}
void oled_disp::display_off()
{
    disp_.set_disp_state(LCD_OFF);
}

Result<> oled_disp::flush_page(std::span<const uint8_t> row, uint8_t page)
{
    if (page >= (screen_height_ >> 3) || row.size() != screen_width_) {
	return Fail(Err::InvalidParam);
    }
    disp_.flush_page(std::span<const uint8_t, 128>(row.data(), row.size()), page);
    return Ok();
}

void oled_disp::flush_page(uint8_t page)
{
    (void)flush_page(std::span<const uint8_t>(&vram_[page * screen_width_], screen_width_), page);
}

void oled_disp::draw_pixel(uint8_t x, uint8_t y, Font::Color color)
{
    if (x >= screen_width_ || y >= screen_height_) {
	return;
    }
    if (color == Font::Color::WHITE) {
	vram_[x + y / 8 * screen_width_] |= 1 << (y % 8);
    } else {
	vram_[x + y / 8 * screen_width_] &= ~(1 << (y % 8));
    }
}

void oled_disp::draw_pixel(uint8_t x, uint8_t y)
{
    draw_pixel(x, y, Font::Color::WHITE);
}

char oled_disp::write_char(char ch, Font::Font_TypeDef font, Font::Color color)
{
    if (ch < 32 || ch > 126) {
	return 0;
    }

    const uint8_t char_width = font.char_width ? font.char_width[ch - 32] : font.width;

    if (screen_width_ < (CurrentX + char_width) || screen_height_ < (CurrentY + font.height)) {
	return 0;
    }

    for (uint32_t i = 0; i < font.height; ++i) {
	const uint16_t row = font.data[(ch - 32) * font.height + i];
	for (uint32_t j = 0; j < char_width; ++j) {
	    draw_pixel(CurrentX + j, CurrentY + i, ((row << j) & 0x8000) ? color : Font::Color::BLACK);
	}
    }
    CurrentX += char_width;
    return ch;
}

char oled_disp::write_string(char *str, Font::Font_TypeDef font, Font::Color color)
{
    while (*str) {
	if (write_char(*str, font, color) != *str) {
	    return *str;
	}
	++str;
    }
    return *str;
}

void oled_disp::clear_page(uint8_t page)
{
    if (page >= (screen_height_ >> 3)) {
	return;
    }
    memset(&vram_[page * screen_width_], 0x00, screen_width_);
}

void oled_disp::fill_page(uint8_t page, uint8_t pattern)
{
    if (page >= (screen_height_ >> 3)) {
	return;
    }
    memset(&vram_[page * screen_width_], pattern, screen_width_);
}

void oled_disp::set_cursor(uint8_t x, uint8_t y)
{
    CurrentX = x;
    CurrentY = y;
}

